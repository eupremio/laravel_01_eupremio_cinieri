        <h2 class="article-title">
            Flessioni: il punto di partenza per costruire forza
        </h2>

        <p class="article-intro">
            Le flessioni sono uno degli esercizi più semplici e allo stesso
            tempo più utili per sviluppare la spinta della parte superiore
            del corpo.
        </p>

        <h3 class="article-subtitle">
            Come eseguire una flessione
        </h3>

        <p class="article-text">
            Posizionati con le mani leggermente più larghe delle spalle e
            mantieni il corpo allineato dalla testa ai piedi.
            Contrai addome e glutei e inizia a piegare i gomiti.
        </p>

        <p class="article-text">
            Scendi in modo controllato mantenendo il corpo stabile.
            Quando il petto si avvicina al pavimento, spingi con le mani
            per tornare alla posizione iniziale.
        </p>

        <h3 class="article-subtitle">
            Quali muscoli lavorano?
        </h3>

        <p class="article-text">
            Le flessioni coinvolgono principalmente pettorali, tricipiti e
            deltoidi anteriori. Addome e muscoli del tronco contribuiscono
            invece a mantenere il corpo stabile durante tutto il movimento.
        </p>

        <h3 class="article-subtitle">
            Come migliorare
        </h3>

        <p class="article-text">
            La cosa più importante è mantenere una tecnica corretta.
            Una serie di ripetizioni eseguite bene è più utile di molte
            ripetizioni eseguite con una postura scorretta.
        </p>

